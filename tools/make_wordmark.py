# make_wordmark.py - the letters of the POLARITY SHIFT wordmark, as convex pieces. Writes src/ui/WordmarkGlyphs.h (included by src/ui/Wordmark.cpp).
#   python tools/make_wordmark.py            (from the project root)
#   python tools/make_wordmark.py --check    exact test (needs shapely): no two pieces of a letter may overlap (they would show a seam while the logo fades in)
#   python tools/make_wordmark.py --png out.png   a proof sheet (needs pillow)
# Rules of the font: cap height 1.0 (y down, 0 = top), one stroke weight T, hard cuts only (45 degree chamfers, no curves); every piece is CONVEX
# (the renderer fans polygons) and pieces share edges but never overlap. The italic lean is applied when drawing (Wordmark.cpp), not here.
import sys

T = 0.23    # stroke
C = 0.12    # chamfer


def rect(x0, y0, x1, y1, ch=()):
    """a rectangle, clockwise from the top-left; ch = the corners that are cut: 'tl', 'tr', 'br', 'bl'"""
    p = []
    p += [(x0, y0 + C), (x0 + C, y0)] if 'tl' in ch else [(x0, y0)]
    p += [(x1 - C, y0), (x1, y0 + C)] if 'tr' in ch else [(x1, y0)]
    p += [(x1, y1 - C), (x1 - C, y1)] if 'br' in ch else [(x1, y1)]
    p += [(x0 + C, y1), (x0, y1 - C)] if 'bl' in ch else [(x0, y1)]
    return p


def A_glyph():
    w, a = 0.92, 0.22
    xl = lambda y: T + a * (1 - y)          # inner edge of the left leg
    xr = lambda y: w - T - a * (1 - y)      # inner edge of the right leg
    y0, y1 = 0.58, 0.58 + 0.21
    return w, [
        [(0, 1), (T, 1), (a + T, 0), (a, 0)],
        [(w, 1), (w - T, 1), (w - a - T, 0), (w - a, 0)],
        [(xl(y0), y0), (xr(y0), y0), (xr(y1), y1), (xl(y1), y1)],
    ]


GLYPHS = {}
# P
w = 0.68
GLYPHS['P'] = (w, [rect(0, 0, T, 1, ('tl',)), rect(T, 0, w, T, ('tr',)), rect(w - T, T, w, 0.58, ('br',)), rect(T, 0.58 - T, w - T, 0.58)])
# O (wide: its counter holds the emblem)
w = 0.94
GLYPHS['O'] = (w, [rect(0, 0, w, T, ('tl', 'tr')), rect(0, 1 - T, w, 1, ('bl', 'br')), rect(0, T, T, 1 - T), rect(w - T, T, w, 1 - T)])
# L
w = 0.62
GLYPHS['L'] = (w, [rect(0, 0, T, 1 - T, ('tl',)), rect(0, 1 - T, w, 1, ('bl', 'br'))])
# A
GLYPHS['A'] = A_glyph()
# R
w = 0.72
GLYPHS['R'] = (w, [rect(0, 0, T, 1, ('tl',)), rect(T, 0, w, T, ('tr',)), rect(w - T, T, w, 0.58, ('br',)), rect(T, 0.58 - T, w - T, 0.58),
                   [(0.26, 0.58), (0.58, 0.58), (w, 1), (0.40, 1)]])
# I
GLYPHS['I'] = (T, [rect(0, 0, T, 1, ('tl', 'br'))])
# T
w = 0.82
GLYPHS['T'] = (w, [rect(0, 0, w, T, ('tl', 'tr')), rect((w - T) / 2, T, (w + T) / 2, 1, ('br',))])
# Y
w = 0.86
cx, sy = w / 2, 0.52
GLYPHS['Y'] = (w, [[(0, 0), (0.31, 0), (cx, sy), (cx - T / 2, sy)], [(w, 0), (w - 0.31, 0), (cx, sy), (cx + T / 2, sy)], rect(cx - T / 2, sy, cx + T / 2, 1, ('br',))])
# S
w = 0.72
GLYPHS['S'] = (w, [rect(0, 0, w, T, ('tl', 'tr')), rect(0, T, T, 0.615), rect(T, 0.385, w, 0.615), rect(w - T, 0.615, w, 1 - T), rect(0, 1 - T, w, 1, ('bl', 'br'))])
# H
w = 0.78
GLYPHS['H'] = (w, [rect(0, 0, T, 1, ('tl',)), rect(w - T, 0, w, 1, ('br',)), rect(T, 0.5 - T / 2, w - T, 0.5 + T / 2)])
# F
w = 0.64
GLYPHS['F'] = (w, [rect(0, 0, T, 1, ('tl', 'bl')), rect(T, 0, w, T, ('tr',)), rect(T, 0.46, w - 0.12, 0.46 + T)])


def write_header(path):
    lines = ['#pragma once',
             '// GENERATED by tools/make_wordmark.py - do not edit by hand. Letters of the POLARITY SHIFT wordmark as convex pieces (cap height 1, y down).',
             'struct GlyphPiece { int count; float p[10][2]; };', 'struct Glyph { char letter; float width; int pieces; GlyphPiece piece[6]; };',
             'static const Glyph GLYPHS[] = {']
    for ch, (w, polys) in GLYPHS.items():
        lines.append(f'    {{\'{ch}\', {w:.4f}f, {len(polys)}, {{')
        for pl in polys:
            assert len(pl) <= 10 and len(polys) <= 6
            pts = ', '.join(f'{{{x:.4f}f, {y:.4f}f}}' for x, y in pl)
            lines.append(f'        {{{len(pl)}, {{{pts}}}}},')
        lines.append('    }},')
    lines.append('};')
    lines.append(f'static const float STROKE = {T}f;')
    open(path, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')


def is_convex(pl):
    s = 0
    for i in range(len(pl)):
        a, b, c = pl[i], pl[(i + 1) % len(pl)], pl[(i + 2) % len(pl)]
        cr = (b[0] - a[0]) * (c[1] - b[1]) - (b[1] - a[1]) * (c[0] - b[0])
        if abs(cr) < 1e-9:
            continue
        if s == 0:
            s = 1 if cr > 0 else -1
        elif (cr > 0) != (s > 0):
            return False
    return True


def check():
    from shapely.geometry import Polygon
    bad = 0
    for ch, (w, polys) in GLYPHS.items():
        ps = [Polygon(pl) for pl in polys]
        worst = 0.0
        for i in range(len(ps)):
            if not is_convex(polys[i]):
                print('NOT CONVEX', ch, polys[i]); bad += 1
            for j in range(i + 1, len(ps)):
                worst = max(worst, ps[i].intersection(ps[j]).area)
        print(f'{ch}: width {w:.2f}  pieces {len(polys)}  worst overlap {worst:.5f}')
        if worst > 1e-6:
            bad += 1
    return bad


def sheet(path):
    from PIL import Image, ImageDraw
    S = 220
    im = Image.new('RGB', (S * 7, S * 2), (20, 20, 28)); d = ImageDraw.Draw(im)
    for i, ch in enumerate(GLYPHS):
        w, polys = GLYPHS[ch]
        ox, oy = (i % 7) * S + 30, (i // 7) * S + 20
        for pl in polys:
            d.polygon([(ox + (x + 0.16 * (1 - y)) * 150, oy + y * 150) for x, y in pl], fill=(240, 240, 245))
    im.save(path)


if __name__ == '__main__':
    import os
    here = os.path.dirname(os.path.abspath(__file__))
    write_header(os.path.join(here, '..', 'src', 'ui', 'WordmarkGlyphs.h'))
    if '--check' in sys.argv:
        sys.exit(1 if check() else 0)
    if '--png' in sys.argv:
        sheet(sys.argv[sys.argv.index('--png') + 1])
